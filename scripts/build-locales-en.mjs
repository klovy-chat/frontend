let untranslated = 0;
function countUntranslated(obj, path = "") {
  if (typeof obj === "string") {
    if (/[ąćęłńóśźżĄĆĘŁŃÓŚŹŻ]/.test(obj)) {
      untranslated++;
      if (untranslated <= 10) console.warn("untranslated:", path, obj);
    }
    return;
  }
  for (const [k, v] of Object.entries(obj)) countUntranslated(v, path ? `${path}.${k}` : k);
}
