function deepTranslate(obj, path = "") {
  if (typeof obj === "string") {
    return translateString(obj, path);
  }
  if (Array.isArray(obj)) return obj.map((v, i) => deepTranslate(v, `${path}[${i}]`));
  const out = {};
  for (const [k, v] of Object.entries(obj)) out[k] = deepTranslate(v, path ? `${path}.${k}` : k);
  return out;
}

